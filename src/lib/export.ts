import Papa from "papaparse";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

export function toCSV(rows: Record<string, unknown>[]): string {
  return Papa.unparse(rows);
}

export function downloadFile(content: string, filename: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export function parseCSV<T = Record<string, string>>(file: File): Promise<T[]> {
  return new Promise((resolve, reject) => {
    Papa.parse(file, {
      header: true,
      skipEmptyLines: true,
      complete: (res) => resolve(res.data as T[]),
      error: (err: Error) => reject(err)
    });
  });
}

export interface PdfSection {
  title: string;
  head: string[][];
  body: (string | number)[][];
  foot?: (string | number)[][];
}

export function exportPDF(opts: {
  title: string;
  subtitle?: string;
  sections: PdfSection[];
  filename: string;
}) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // branded header
  doc.setFillColor(11, 18, 38);
  doc.rect(0, 0, pageWidth, 30, "F");
  doc.setTextColor(246, 196, 83);
  doc.setFontSize(8);
  doc.text("MAXHALS FORENSICS • FORENSIC AUDIT • ADVISORY • BIG DATA ANALYTICS", 14, 10);
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.text(opts.title, 14, 21);
  if (opts.subtitle) {
    doc.setFontSize(9);
    doc.setTextColor(120, 130, 160);
    doc.text(opts.subtitle, 14, 27);
  }

  let y = 38;
  opts.sections.forEach((sec) => {
    if (y > 250) {
      doc.addPage();
      y = 20;
    }
    doc.setTextColor(26, 39, 82);
    doc.setFontSize(11);
    doc.text(sec.title, 14, y);
    autoTable(doc, {
      startY: y + 2,
      head: sec.head,
      body: sec.body,
      foot: sec.foot,
      theme: "grid",
      headStyles: { fillColor: [26, 39, 82], textColor: [255, 255, 255], fontSize: 8 },
      footStyles: { fillColor: [51, 214, 194], textColor: [7, 12, 27], fontSize: 8 },
      styles: { fontSize: 8, cellPadding: 2.2 },
      alternateRowStyles: { fillColor: [242, 244, 249] }
    });
    const last = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable;
    y = (last?.finalY ?? y + 10) + 10;
  });

  doc.setFontSize(7);
  doc.setTextColor(130, 140, 170);
  doc.text(
    `Generated by Maxhals Forensics Suite for Tatenda Makuvaza • ${new Date().toLocaleString()} • VAT 100245781-Z • +263 782 514 255`,
    14,
    doc.internal.pageSize.getHeight() - 8
  );

  doc.save(opts.filename);
}
